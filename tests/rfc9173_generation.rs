//! RFC 9173 Bundle Generation Tests
//!
//! These tests generate bundles with BIB/BCB using internal generation APIs
//! and verify byte-for-byte reproduction of RFC 9173 Appendix A examples.
//!
//! Requires `test-fixtures` feature for access to internal generation functions.
#![cfg(all(feature = "bpsec-default", feature = "test-fixtures"))]

use interplanetary_sdk::{
    bp::*,
    security::{self, AesGcmVariant, HmacKeyLengthPolicy, HmacVariant, bib},
    types::*,
};
use std::fs;

#[test]
fn test_a1_generate_bundle_with_bib() {
    // Load RFC test vectors
    // NOTE: Uses Rfc9173AppendixAVectors policy - RFC A.1 uses 16-byte key violating §3.5
    let vectors: serde_json::Value =
        serde_json::from_str(&fs::read_to_string("spec/rfc9173_test_vectors.json").unwrap())
            .unwrap();

    let a1 = &vectors["vectors"][0];
    assert_eq!(a1["section"], "A.1.3.1");

    // Extract RFC values
    let key = hex::decode(a1["key"].as_str().unwrap()).unwrap();
    let expected_final = hex::decode(a1["final_bundle"].as_str().unwrap()).unwrap();
    let expected_ippt = hex::decode(a1["ippt"].as_str().unwrap()).unwrap();
    let _expected_sig = hex::decode(a1["signature"].as_str().unwrap()).unwrap();
    let payload_data = hex::decode(a1["payload_data"].as_str().unwrap()).unwrap();

    // Build original bundle (RFC A.1.1.1)
    // Per RFC: source ipn:2.1, dest ipn:1.2
    // Creation: time=0 (no accurate clock), sequence=40
    // Lifetime: 1,000,000 milliseconds
    let source = EndpointId::ipn(0, 2, 1).unwrap();
    let dest = EndpointId::ipn(0, 1, 2).unwrap();
    let timestamp = CreationTimestamp::new(DtnTimeMs::from_millis(0), 40);
    let lifetime = 1000000;

    let mut bundle = BundleBuilder::new()
        .source(source.clone())
        .destination(dest)
        .creation_timestamp(timestamp)
        .lifetime(lifetime)
        .payload(payload_data.clone())
        .build()
        .unwrap();

    // Construct IPPT and verify it matches RFC
    let ippt = bib::construct_ippt(&bundle, 1, 0x00).unwrap();

    // Note: IPPT may not match yet due to encoding differences
    // This test documents the gap
    if ippt != expected_ippt {
        eprintln!("WARNING: IPPT mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_ippt.len(),
            hex::encode(&expected_ippt)
        );
        eprintln!("Got      ({} bytes): {}", ippt.len(), hex::encode(&ippt));
    }

    // Generate BIB
    use interplanetary_sdk::security::HmacKeyLengthPolicy;
    let bib_config = bib::BibConfig {
        security_source: source.clone(),
        targets: bib::BibTargets {
            block_numbers: vec![1], // Target payload block
        },
        sha_variant: HmacVariant::Sha512,
        key: key.clone(),
        scope_flags: 0x00,
        wrapped_key: None,
        skip_source_validation: true, // RFC 9173 test vectors use node numbers in Private Use range
        hmac_key_policy: Some(HmacKeyLengthPolicy::Rfc9173AppendixAVectors),
    };

    let bib_block = bib::generate_bib(&bundle, &bib_config).unwrap();

    // Insert BIB into bundle (assign block number)
    let mut bib_with_num = bib_block;
    bib_with_num.block_number = 2; // Per RFC A.1.3.3 Figure 7, BIB is block 2

    // Insert BIB before payload
    bundle.blocks.insert(0, bib_with_num);

    // Encode final bundle
    let generated = BundleCodec::encode(&bundle).unwrap();

    // Compare with RFC final bundle
    if generated != expected_final {
        eprintln!("GENERATION MISMATCH:");
        eprintln!("Expected ({} bytes):", expected_final.len());
        eprintln!("{}", hex::encode(&expected_final));
        eprintln!("\nGenerated ({} bytes):", generated.len());
        eprintln!("{}", hex::encode(&generated));

        // Find first difference
        for (i, (e, g)) in expected_final.iter().zip(generated.iter()).enumerate() {
            if e != g {
                eprintln!(
                    "\nFirst diff at byte {}: expected {:02x}, got {:02x}",
                    i, e, g
                );
                break;
            }
        }

        panic!("Bundle generation does not match RFC 9173 A.1 byte-for-byte");
    }

    println!("✓ RFC 9173 A.1 bundle generated byte-for-byte");
}

#[test]
fn test_a2_generate_bundle_with_bcb() {
    // Load RFC test vectors
    let vectors: serde_json::Value =
        serde_json::from_str(&fs::read_to_string("spec/rfc9173_test_vectors.json").unwrap())
            .unwrap();

    let a2 = &vectors["vectors"][1];
    assert_eq!(a2["section"], "A.2.3.1");

    // Extract RFC values
    let content_key = hex::decode(a2["content_encryption_key"].as_str().unwrap()).unwrap();
    let _kek = hex::decode(a2["key_encryption_key"].as_str().unwrap()).unwrap();
    let iv = hex::decode(a2["iv"].as_str().unwrap()).unwrap();
    let wrapped_key = hex::decode(a2["aes_wrapped_key"].as_str().unwrap()).unwrap();
    let expected_final = hex::decode(a2["final_bundle"].as_str().unwrap()).unwrap();
    let expected_aad = hex::decode(a2["aad"].as_str().unwrap()).unwrap();
    let _expected_auth_tag = hex::decode(a2["authentication_tag"].as_str().unwrap()).unwrap();
    let payload_data = hex::decode(a2["payload_data"].as_str().unwrap()).unwrap();
    let expected_ciphertext = hex::decode(a2["payload_ciphertext"].as_str().unwrap()).unwrap();

    // Build original bundle (RFC A.2.1 - identical to A.1)
    // Primary block same as A.1: source ipn:2.1, dest ipn:1.2, timestamp [0,40], lifetime 1000000
    let source = EndpointId::ipn(0, 2, 1).unwrap();
    let dest = EndpointId::ipn(0, 1, 2).unwrap();
    let timestamp = CreationTimestamp::new(DtnTimeMs::from_millis(0), 40);
    let lifetime = 1000000;

    let mut bundle = BundleBuilder::new()
        .source(source.clone())
        .destination(dest)
        .creation_timestamp(timestamp)
        .lifetime(lifetime)
        .payload(payload_data.clone())
        .build()
        .unwrap();

    // Construct AAD and verify it matches RFC
    let aad = security::bcb::construct_aad(&bundle, 1, 2, 0x00).unwrap();

    if aad != expected_aad {
        eprintln!("WARNING: AAD mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_aad.len(),
            hex::encode(&expected_aad)
        );
        eprintln!("Got      ({} bytes): {}", aad.len(), hex::encode(&aad));
    }

    // Generate BCB
    let bcb_config = security::bcb::BcbConfig {
        security_source: source.clone(),
        targets: security::bcb::BcbTargets {
            block_numbers: vec![1], // Target payload block
        },
        aes_variant: AesGcmVariant::Aes128, // A128GCM
        key: content_key.clone(),
        iv: iv.clone(),
        wrapped_key: Some(wrapped_key.clone()),
        scope_flags: 0x00,
        key_id: None,
        skip_source_validation: true, // RFC 9173 test vectors use node numbers in Private Use range
    };

    let (bcb_block, ciphertexts) = security::bcb::generate_bcb(&bundle, &bcb_config, None).unwrap();

    // Verify ciphertext matches RFC
    if ciphertexts[0] != expected_ciphertext {
        eprintln!("WARNING: Ciphertext mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_ciphertext.len(),
            hex::encode(&expected_ciphertext)
        );
        eprintln!(
            "Got      ({} bytes): {}",
            ciphertexts[0].len(),
            hex::encode(&ciphertexts[0])
        );
    }

    // Insert BCB into bundle (assign block number 2 per RFC A.2.3.3)
    let mut bcb_with_num = bcb_block;
    bcb_with_num.block_number = 2;

    // Replace payload with encrypted version
    bundle.blocks[0].data = ciphertexts[0].clone();

    // Insert BCB before payload
    bundle.blocks.insert(0, bcb_with_num);

    // Encode final bundle
    let generated = BundleCodec::encode(&bundle).unwrap();

    // Compare with RFC final bundle
    if generated != expected_final {
        eprintln!("GENERATION MISMATCH:");
        eprintln!("Expected ({} bytes):", expected_final.len());
        eprintln!("{}", hex::encode(&expected_final));
        eprintln!("\nGenerated ({} bytes):", generated.len());
        eprintln!("{}", hex::encode(&generated));

        // Find first difference
        for (i, (e, g)) in expected_final.iter().zip(generated.iter()).enumerate() {
            if e != g {
                eprintln!(
                    "\nFirst diff at byte {}: expected {:02x}, got {:02x}",
                    i, e, g
                );
                break;
            }
        }

        panic!("Bundle generation does not match RFC 9173 A.2 byte-for-byte");
    }

    println!("✓ RFC 9173 A.2 bundle generated byte-for-byte");
}

#[test]
fn test_a3_generate_multi_source_security() {
    // Load RFC test vectors
    // NOTE: Uses Rfc9173AppendixAVectors policy - RFC A.3 uses 16-byte key violating §3.5
    let vectors: serde_json::Value =
        serde_json::from_str(&fs::read_to_string("spec/rfc9173_test_vectors.json").unwrap())
            .unwrap();

    let a3 = &vectors["vectors"][2];
    assert_eq!(a3["section"], "A.3");

    // Extract RFC values
    let expected_final = hex::decode(a3["final_bundle"].as_str().unwrap()).unwrap();

    // BIB values (from ipn:3.0)
    let bib_key = hex::decode(a3["bib_key"].as_str().unwrap()).unwrap();
    let expected_primary_ippt = hex::decode(a3["bib_primary_ippt"].as_str().unwrap()).unwrap();
    let expected_age_ippt = hex::decode(a3["bib_bundle_age_ippt"].as_str().unwrap()).unwrap();
    let _expected_primary_sig = hex::decode(a3["bib_primary_signature"].as_str().unwrap()).unwrap();
    let _expected_age_sig = hex::decode(a3["bib_bundle_age_signature"].as_str().unwrap()).unwrap();

    // BCB values (from ipn:2.1)
    let bcb_key = hex::decode(a3["bcb_cek"].as_str().unwrap()).unwrap();
    let bcb_iv = hex::decode(a3["bcb_iv"].as_str().unwrap()).unwrap();
    let expected_bcb_aad = hex::decode(a3["bcb_aad"].as_str().unwrap()).unwrap();
    let expected_ciphertext = hex::decode(a3["bcb_payload_ciphertext"].as_str().unwrap()).unwrap();
    let _expected_tag = hex::decode(a3["bcb_authentication_tag"].as_str().unwrap()).unwrap();
    let payload_data = hex::decode(a3["bcb_payload_data"].as_str().unwrap()).unwrap();

    // Build original bundle (RFC A.3.1)
    // Primary: source ipn:2.1, dest ipn:1.2, timestamp [0,40], lifetime 1000000
    let source_ipn2 = EndpointId::ipn(0, 2, 1).unwrap();
    let source_ipn3 = EndpointId::ipn(0, 3, 0).unwrap();
    let dest = EndpointId::ipn(0, 1, 2).unwrap();
    let timestamp = CreationTimestamp::new(DtnTimeMs::from_millis(0), 40);
    let lifetime = 1000000;

    let mut bundle = BundleBuilder::new()
        .source(source_ipn2.clone())
        .destination(dest)
        .creation_timestamp(timestamp)
        .lifetime(lifetime)
        .payload(payload_data.clone())
        .build()
        .unwrap();

    // Add Bundle Age extension block (block type 7, age = 300ms)
    // Per RFC A.3.1.2: age value 300, encoded as CBOR uint then wrapped in bytes
    let mut age_data = Vec::new();
    ciborium::into_writer(&ciborium::Value::Integer(300.into()), &mut age_data).unwrap();

    let age_block = CanonicalBlock {
        block_type: BlockType::BundleAge,
        block_number: 2,
        block_flags: 0,
        crc_type: CrcType::None,
        data: age_data,
    };

    // Insert age block before payload (it will be at index 0, payload at 1)
    bundle.blocks.insert(0, age_block);

    // Step 1: Apply BCB from ipn:2.1 to payload (block 1)
    let bcb_config = security::bcb::BcbConfig {
        security_source: source_ipn2.clone(),
        targets: security::bcb::BcbTargets {
            block_numbers: vec![1], // Payload block
        },
        aes_variant: AesGcmVariant::Aes128,
        key: bcb_key.clone(),
        iv: bcb_iv.clone(),
        wrapped_key: None, // A.3 doesn't use wrapped key
        scope_flags: 0x00,
        key_id: None,
        skip_source_validation: true, // RFC 9173 test vectors use node numbers in Private Use range
    };

    // Verify AAD matches RFC
    let bcb_aad = security::bcb::construct_aad(&bundle, 1, 4, 0x00).unwrap();
    if bcb_aad != expected_bcb_aad {
        eprintln!("WARNING: BCB AAD mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_bcb_aad.len(),
            hex::encode(&expected_bcb_aad)
        );
        eprintln!(
            "Got      ({} bytes): {}",
            bcb_aad.len(),
            hex::encode(&bcb_aad)
        );
    }

    let (bcb_block, ciphertexts) = security::bcb::generate_bcb(&bundle, &bcb_config, None).unwrap();

    // Verify ciphertext matches RFC
    if ciphertexts[0] != expected_ciphertext {
        eprintln!("WARNING: Ciphertext mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_ciphertext.len(),
            hex::encode(&expected_ciphertext)
        );
        eprintln!(
            "Got      ({} bytes): {}",
            ciphertexts[0].len(),
            hex::encode(&ciphertexts[0])
        );
    }

    // Replace payload with encrypted version
    bundle.blocks[1].data = ciphertexts[0].clone();

    // Assign BCB block number and insert (per RFC: BCB is block 4)
    let mut bcb_with_num = bcb_block;
    bcb_with_num.block_number = 4;

    // Step 2: Apply BIB from ipn:3.0 to primary (0) and age (2)
    let bib_config = bib::BibConfig {
        security_source: source_ipn3.clone(),
        targets: bib::BibTargets {
            block_numbers: vec![0, 2], // Primary and age blocks
        },
        sha_variant: HmacVariant::Sha256, // HMAC 256/256
        key: bib_key.clone(),
        scope_flags: 0x00,
        wrapped_key: None,
        skip_source_validation: true, // RFC 9173 test vectors use node numbers in Private Use range
        hmac_key_policy: Some(HmacKeyLengthPolicy::Rfc9173AppendixAVectors),
    };

    // Verify IPPTs match RFC
    let primary_ippt = bib::construct_ippt(&bundle, 0, 0x00).unwrap();
    if primary_ippt != expected_primary_ippt {
        eprintln!("WARNING: Primary IPPT mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_primary_ippt.len(),
            hex::encode(&expected_primary_ippt)
        );
        eprintln!(
            "Got      ({} bytes): {}",
            primary_ippt.len(),
            hex::encode(&primary_ippt)
        );
    }

    let age_ippt = bib::construct_ippt(&bundle, 2, 0x00).unwrap();
    if age_ippt != expected_age_ippt {
        eprintln!("WARNING: Age IPPT mismatch");
        eprintln!(
            "Expected ({} bytes): {}",
            expected_age_ippt.len(),
            hex::encode(&expected_age_ippt)
        );
        eprintln!(
            "Got      ({} bytes): {}",
            age_ippt.len(),
            hex::encode(&age_ippt)
        );
    }

    let bib_block = bib::generate_bib(&bundle, &bib_config).unwrap();

    // Assign BIB block number (per RFC: BIB is block 3)
    let mut bib_with_num = bib_block;
    bib_with_num.block_number = 3;

    // Insert security blocks in order: BIB (3) then BCB (4), both before age/payload
    bundle.blocks.insert(0, bib_with_num);
    bundle.blocks.insert(1, bcb_with_num);

    // Final bundle structure: Primary + BIB(3) + BCB(4) + Age(2) + Payload(1, encrypted)

    // Encode and compare
    let generated = BundleCodec::encode(&bundle).unwrap();

    if generated != expected_final {
        eprintln!("GENERATION MISMATCH:");
        eprintln!("Expected ({} bytes):", expected_final.len());
        eprintln!("{}", hex::encode(&expected_final));
        eprintln!("\nGenerated ({} bytes):", generated.len());
        eprintln!("{}", hex::encode(&generated));

        // Find first difference
        for (i, (e, g)) in expected_final.iter().zip(generated.iter()).enumerate() {
            if e != g {
                eprintln!(
                    "\nFirst diff at byte {}: expected {:02x}, got {:02x}",
                    i, e, g
                );
                break;
            }
        }

        panic!("Bundle generation does not match RFC 9173 A.3 byte-for-byte");
    }

    println!("✓ RFC 9173 A.3 bundle generated byte-for-byte");
}
